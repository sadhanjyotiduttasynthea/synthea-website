/**
 * Finds logo files uploaded to public/images/brand and public/images/supporters,
 * trims surrounding white space, makes plain white backgrounds transparent, and
 * writes web-ready copies to public/images/generated/. It then writes
 * src/content/brand-assets.generated.ts so the site uses them automatically.
 *
 * Runs before `dev`, `build` and `typecheck`. Upload any of:
 *   public/images/brand/      a file whose name contains "synthea"  (company logo)
 *   public/images/supporters/ a file whose name contains "genopole"
 *   public/images/supporters/ a file whose name contains "agro"     (AgroParisTech)
 * Formats: .png .jpg .jpeg .webp .svg
 */
import { readdir, mkdir, copyFile, writeFile, readFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const outDir = path.join(root, "public/images/generated");
const exts = [".png", ".jpg", ".jpeg", ".webp", ".svg"];

const wanted = [
  { key: "synthea", dir: "public/images/brand", match: /synthea/i, mode: "mono" },
  { key: "genopole", dir: "public/images/supporters", match: /genopole/i, mode: "color" },
  { key: "agroparistech", dir: "public/images/supporters", match: /agro/i, mode: "color" },
];

async function findFile(dir, match) {
  const abs = path.join(root, dir);
  if (!existsSync(abs)) return null;
  const files = (await readdir(abs)).filter((f) => match.test(f) && exts.includes(path.extname(f).toLowerCase()));
  files.sort();
  return files.length ? path.join(abs, files[0]) : null;
}

async function processRaster(sharp, src, key, mode) {
  const trimmed = await sharp(src).flatten({ background: "#ffffff" }).trim({ threshold: 12 }).toBuffer();
  const { data, info } = await sharp(trimmed).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  for (let i = 0; i < data.length; i += 4) {
    const r = data[i], g = data[i + 1], b = data[i + 2];
    if (mode === "mono") {
      // Black-on-white logo → solid black with alpha from darkness (smooth edges).
      const lum = 0.2126 * r + 0.7152 * g + 0.0722 * b;
      data[i] = data[i + 1] = data[i + 2] = 17;
      data[i + 3] = Math.max(0, Math.min(255, Math.round(255 - lum)));
    } else if (r > 245 && g > 245 && b > 245) {
      data[i + 3] = 0; // plain white background → transparent
    }
  }
  const pad = Math.round(Math.max(info.width, info.height) * 0.02);
  const out = path.join(outDir, `${key}.png`);
  const img = sharp(data, { raw: { width: info.width, height: info.height, channels: 4 } })
    .extend({ top: pad, bottom: pad, left: pad, right: pad, background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .resize({ height: Math.min(info.height + 2 * pad, 360), withoutEnlargement: true });
  const meta = await img.png({ compressionLevel: 9 }).toFile(out);
  return { src: `/images/generated/${key}.png`, width: meta.width, height: meta.height };
}

async function main() {
  await mkdir(outDir, { recursive: true });
  let sharp = null;
  try {
    sharp = (await import("sharp")).default;
  } catch {
    console.warn("[brand-assets] sharp not available — raster logos will be copied without trimming.");
  }

  const result = {};
  for (const w of wanted) {
    const file = await findFile(w.dir, w.match);
    if (!file) {
      result[w.key] = null;
      continue;
    }
    const ext = path.extname(file).toLowerCase();
    try {
      if (ext === ".svg" || !sharp) {
        const dest = path.join(outDir, `${w.key}${ext}`);
        await copyFile(file, dest);
        let width = 400;
        let height = 120;
        if (ext === ".svg") {
          const vb = (await readFile(file, "utf8")).match(/viewBox="[\d.\s-]*?([\d.]+)\s+([\d.]+)"/);
          if (vb) [width, height] = [Math.round(+vb[1]), Math.round(+vb[2])];
        } else if (sharp) {
          const m = await sharp(file).metadata();
          [width, height] = [m.width ?? width, m.height ?? height];
        }
        result[w.key] = { src: `/images/generated/${w.key}${ext}`, width, height };
      } else {
        result[w.key] = await processRaster(sharp, file, w.key, w.mode);
      }
      console.log(`[brand-assets] ${w.key}: ${path.relative(root, file)} → ${result[w.key].src}`);
    } catch (err) {
      console.warn(`[brand-assets] could not process ${file}:`, err.message);
      result[w.key] = null;
    }
  }

  const ts = `// Generated by scripts/prepare-brand-assets.mjs — do not edit by hand.
export type BrandAsset = { src: string; width: number; height: number } | null;

export const brandAssets: { synthea: BrandAsset; genopole: BrandAsset; agroparistech: BrandAsset } = ${JSON.stringify(result, null, 2)};
`;
  const target = path.join(root, "src/content/brand-assets.generated.ts");
  const prev = existsSync(target) ? await readFile(target, "utf8") : "";
  if (prev !== ts) await writeFile(target, ts);
}

main();
